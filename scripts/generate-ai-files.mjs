// Regenerates, from the library sources:
//   plugins/xeerpe/skills/xeerpe/references/api.md and presets.md   (Claude skill)
//   plugins/xeerpe/.claude-plugin/plugin.json                       (version only)
//   lib/AGENTS.md                                                   (shipped in the npm package, for any coding agent)
//   doc/public/llms-full.txt                                        (served at xeerpe.io/llms-full.txt, for web-enabled AIs)
// Run after `npm run build:lib`:  node scripts/generate-ai-files.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const skillDir = 'plugins/xeerpe/skills/xeerpe'
const out = join(root, skillDir, 'references')
mkdirSync(out, { recursive: true })

const read = (p) => readFileSync(join(root, p), 'utf8').trim()
const { presetCategories, presetNames, colors } = await import(pathToFileURL(join(root, 'lib/dist/index.mjs')).href)

const version = JSON.parse(read('lib/package.json')).version

const models = ['gradient', 'pattern', 'effects', 'filters', 'animation']
const validations = ['color', 'angle', 'backgroundSize', 'cssPosition', 'directions', 'position', 'radial']

const api = [
    `# xeerpe API reference (v${version})`,
    '',
    '> Generated file. Do not edit by hand.',
    '',
    '## Builder methods',
    '',
    'Every method returns the builder, so calls chain. Shortcut methods take optional options; the generic ones require them.',
    '',
    '| Method | Options type |',
    '| --- | --- |',
    ...[
        [
            'linearGradient / radialGradient / conicGradient / meshGradient',
            'LinearGradientOptions / RadialGradientOptions / ConicGradientOptions / MeshGradientOptions (required)',
        ],
        ['gradient(type, options)', 'GradientOptions'],
        ['dots / grid / stars / rays', 'DotsOptions / GridOptions / StarsOptions / RaysOptions (optional)'],
        ['noise / vignette / grain / glow', 'NoiseOptions / VignetteOptions / GrainOptions / GlowOptions (optional)'],
        ['blur', 'BlurOptions (optional)'],
        ['pulse / rotate / breathe / aurora / shimmer / liquid / plasma / float / drift', 'AnimationOptions (optional)'],
        ['pattern / effect / filter / animation (type, options)', 'generic forms, options required (pass {})'],
        ['toStyle()', 'Record<string, string>, camelCase CSS properties'],
        ['toTextStyle()', 'Record<string, string>, gradient-filled text'],
    ].map(([m, o]) => `| \`${m}\` | ${o} |`),
    '',
    '`new Preset(name)` extends `Builder`; unknown names throw `Preset "<name>" not found`.',
    '',
    '## Option types (from lib/src/models)',
    '',
    ...models.flatMap((m) => [`### ${m}.ts`, '', '```ts', read(`lib/src/models/${m}.ts`), '```', '']),
    '## Input validation (from lib/src/validations)',
    '',
    'Values that fail these checks are rejected by the builder. Keep inputs inside these shapes.',
    '',
    ...validations.flatMap((v) => [`### ${v}.ts`, '', '```ts', read(`lib/src/validations/${v}.ts`), '```', '']),
]
writeFileSync(join(out, 'api.md'), api.join('\n'))

const presets = [
    `# xeerpe presets (${presetNames.length}, v${version})`,
    '',
    '> Generated file. Do not edit by hand.',
    '',
    "Usage: `new Preset('name').toStyle()`. Names are kebab-case and case-sensitive. A preset is a `Builder`, so you can keep chaining (`.grain()`, `.vignette()`, animations).",
    '',
    'Category hints: `pastel`, `sky`, `neutral` are mostly light backgrounds (pair with dark text); `neon`, `space`, `luxury`, `moods` are mostly dark. Check the preview on xeerpe.io/guide/presets-examples when unsure.',
    '',
    ...Object.entries(presetCategories).flatMap(([cat, names]) => [
        `## ${cat} (${names.length})`,
        '',
        names.map((n) => `\`${n}\``).join(', '),
        '',
    ]),
    '## Palette (`colors`)',
    '',
    "`import { colors } from 'xeerpe'` gives named hex values: " +
        Object.keys(colors)
            .map((k) => `\`${k}\``)
            .join(', '),
    '',
]
writeFileSync(join(out, 'presets.md'), presets.join('\n'))
// Portable bundles: the skill body without Claude-specific frontmatter and reference links.
const skillBody = read(`${skillDir}/SKILL.md`)
    .replace(/^---[\s\S]*?---\n/, '')
    .trim()
    .split('\n## References')[0]
    .replace(/^# xeerpe\n+/, '')
    .replace(/\[[^\]]+\]\(references\/[^)]+\)/g, 'the sections below')
    .trim()

const section = (file) =>
    read(`${skillDir}/references/${file}`)
        .replace(/^> Generated by.*\n?/m, '')
        .replace(/^(#{1,5}) /gm, '$1# ')
        .trim()

const agents = [
    '# xeerpe: instructions for AI coding agents',
    '',
    `> Generated by scripts/generate-ai-files.mjs (xeerpe v${version}). Full reference: https://xeerpe.io/llms-full.txt`,
    '',
    skillBody,
    '',
    section('animations.md'),
    '',
    section('recipes.md'),
    '',
    'For every option type, the validation rules and the full preset list, read https://xeerpe.io/llms-full.txt or the types shipped in this package.',
    '',
].join('\n')
writeFileSync(join(root, 'lib', 'AGENTS.md'), agents)

const full = [
    `# xeerpe (v${version}): complete reference for AI assistants`,
    '',
    '> Generated by scripts/generate-ai-files.mjs. Docs: https://xeerpe.io. Short index: https://xeerpe.io/llms.txt',
    '',
    skillBody,
    '',
    section('animations.md'),
    '',
    section('recipes.md'),
    '',
    section('api.md'),
    '',
    section('presets.md'),
    '',
].join('\n')
mkdirSync(join(root, 'doc', 'public'), { recursive: true })
writeFileSync(join(root, 'doc', 'public', 'llms-full.txt'), full)

// Keep the plugin version in step with the library, so installed plugins see updates.
const pluginPath = join(root, 'plugins', 'xeerpe', '.claude-plugin', 'plugin.json')
const plugin = JSON.parse(readFileSync(pluginPath, 'utf8'))
plugin.version = version
writeFileSync(pluginPath, `${JSON.stringify(plugin, null, 2)}\n`)

console.log(`written (xeerpe v${version}): references, lib/AGENTS.md, doc/public/llms-full.txt, plugin.json`)
