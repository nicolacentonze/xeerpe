// Regenerates skills/xeerpe/references/api.md and presets.md from the library sources.
// Run after `npm run build:lib`:  node skills/xeerpe/scripts/generate-references.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..')
const out = join(root, 'skills', 'xeerpe', 'references')
mkdirSync(out, { recursive: true })

const read = (p) => readFileSync(join(root, p), 'utf8').trim()
const { presetCategories, presetNames, colors } = await import(pathToFileURL(join(root, 'lib/dist/index.mjs')).href)

const version = JSON.parse(read('lib/package.json')).version

const models = ['gradient', 'pattern', 'effects', 'filters', 'animation']
const validations = ['color', 'angle', 'backgroundSize', 'cssPosition', 'directions', 'position', 'radial']

const api = [
    `# xeerpe API reference (v${version})`,
    '',
    '> Generated by scripts/generate-references.mjs. Do not edit by hand.',
    '',
    '## Builder methods',
    '',
    'Every method returns the builder, so calls chain. Shortcut methods take optional options; the generic ones require them.',
    '',
    '| Method | Options type |',
    '| --- | --- |',
    ...[
        ['linearGradient / radialGradient / conicGradient / meshGradient', 'LinearGradientOptions / RadialGradientOptions / ConicGradientOptions / MeshGradientOptions (required)'],
        ['gradient(type, options)', 'GradientOptions'],
        ['dots / grid / stars / rays', 'DotsOptions / GridOptions / StarsOptions / RaysOptions (optional)'],
        ['noise / vignette / grain / glow', 'NoiseOptions / VignetteOptions / GrainOptions / GlowOptions (optional)'],
        ['blur', 'BlurOptions (optional)'],
        ['pulse / rotate / breathe / aurora / shimmer / liquid / plasma / float / drift', 'AnimationOptions (optional)'],
        ['pattern / effect / filter / animation (type, options)', 'generic forms, options required (pass {})'],
        ['toStyle()', 'Record<string, string>, camelCase CSS properties'],
        ['toTextStyle()', 'Record<string, string>, gradient-filled text'],
    ].map(([m, o]) => `| \`${m}\` | ${o} |`),
    '',
    '`new Preset(name)` extends `Builder`; unknown names throw `Preset "<name>" not found`.',
    '',
    '## Option types (from lib/src/models)',
    '',
    ...models.flatMap((m) => [`### ${m}.ts`, '', '```ts', read(`lib/src/models/${m}.ts`), '```', '']),
    '## Input validation (from lib/src/validations)',
    '',
    'Values that fail these checks are rejected by the builder. Keep inputs inside these shapes.',
    '',
    ...validations.flatMap((v) => [`### ${v}.ts`, '', '```ts', read(`lib/src/validations/${v}.ts`), '```', '']),
]
writeFileSync(join(out, 'api.md'), api.join('\n'))

const presets = [
    `# xeerpe presets (${presetNames.length}, v${version})`,
    '',
    '> Generated by scripts/generate-references.mjs. Do not edit by hand.',
    '',
    "Usage: `new Preset('name').toStyle()`. Names are kebab-case and case-sensitive. A preset is a `Builder`, so you can keep chaining (`.grain()`, `.vignette()`, animations).",
    '',
    'Category hints: `pastel`, `sky`, `neutral` are mostly light backgrounds (pair with dark text); `neon`, `space`, `luxury`, `moods` are mostly dark. Check the preview on xeerpe.io/guide/presets-examples when unsure.',
    '',
    ...Object.entries(presetCategories).flatMap(([cat, names]) => [`## ${cat} (${names.length})`, '', names.map((n) => `\`${n}\``).join(', '), '']),
    '## Palette (`colors`)',
    '',
    "`import { colors } from 'xeerpe'` gives named hex values: " + Object.keys(colors).map((k) => `\`${k}\``).join(', '),
    '',
]
writeFileSync(join(out, 'presets.md'), presets.join('\n'))
console.log(`api.md, presets.md written (${presetNames.length} presets)`)
